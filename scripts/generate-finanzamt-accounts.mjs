// Regenerates src/lib/finanzamtAccounts.ts from the official BMF list of
// Finanzamt bank accounts ("Steuerzahlungen" page).
// Usage: node scripts/generate-finanzamt-accounts.mjs [html-file-or-url]
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCE = 'https://www.bmf.gv.at/themen/steuern/fristen-verfahren/steuerzahlungen.html'
const [input = SOURCE] = process.argv.slice(2)

const src = input.startsWith('http')
  ? await (await fetch(input)).text()
  : readFileSync(input, 'utf8')

const decode = (s) => {
  let out = s
  while (/<[^>]*>/.test(out)) out = out.replace(/<[^>]*>/g, ' ')
  return out
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#(\d+);/g, (_, d) => String.fromCharCode(d))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCharCode(parseInt(h, 16)))
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim()
}

const accounts = []
for (const [, row] of src.matchAll(/<tr[^>]*>(.*?)<\/tr>/gs)) {
  const cells = [...row.matchAll(/<t[dh][^>]*>(.*?)<\/t[dh]>/gs)].map((m) => decode(m[1]))
  const iban = cells.find((c) => /^AT[\d ]{18,26}$/.test(c))
  if (!iban) continue
  const office = cells[0]
  const name = cells[1]
  if (!/^\d{2}$/.test(office) || !name) continue
  accounts.push({ office, name, iban: iban.replace(/ /g, '') })
}

if (accounts.length < 30) {
  console.error(`only ${accounts.length} accounts found – page layout changed?`)
  process.exit(1)
}

const lines = accounts.map(
  (a) =>
    `  { office: ${JSON.stringify(a.office)}, name: ${JSON.stringify(a.name)}, iban: ${JSON.stringify(a.iban)} },`,
)

const out = `// AUTO-GENERATED by scripts/generate-finanzamt-accounts.mjs – do not edit by hand.
// Source: BMF "Steuerzahlungen" (bmf.gv.at), ${accounts.length} official Finanzamt accounts.
import { normalizeIban } from './iban'

export interface FinanzamtAccount {
  /** Dienststellen number – also the first two digits of tax numbers it manages. */
  office: string
  name: string
  iban: string
}

export const FINANZAMT_ACCOUNTS: FinanzamtAccount[] = [
${lines.join('\n')}
]

const BY_IBAN = new Map(FINANZAMT_ACCOUNTS.map((a) => [a.iban, a]))

/** Offline "Verification of Payee" against the official BMF directory. */
export function findFinanzamtAccount(iban: string): FinanzamtAccount | undefined {
  return BY_IBAN.get(normalizeIban(iban))
}

/** "12 345/6789" or "123456789 2604+…" → Dienststellen number "12". */
export function officeFromRemittance(remittance: string): string | undefined {
  const m = /(?:StNr\\.?:?\\s*|^\\s*)(\\d{2})[\\s-]?\\d{3}\\/?\\d{4}\\b/.exec(remittance)
  return m?.[1]
}
`
writeFileSync(new URL('../src/lib/finanzamtAccounts.ts', import.meta.url), out)
console.log(`src/lib/finanzamtAccounts.ts regenerated: ${accounts.length} accounts`)
