// Regenerates src/lib/taxCodes.ts from the official BMF registry
// "Verzeichnis der Abgabenarten" (xlsx, published on bmf.gv.at).
// Usage: node scripts/generate-tax-codes.mjs <Verzeichnis-der-Abgabenarten.xlsx>
import { execSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const [xlsxPath] = process.argv.slice(2)
if (!xlsxPath) {
  console.error('usage: node scripts/generate-tax-codes.mjs <Verzeichnis-der-Abgabenarten.xlsx>')
  process.exit(1)
}

const tmp = mkdtempSync(join(tmpdir(), 'abgabenarten-'))
execSync(`unzip -o -q ${JSON.stringify(xlsxPath)} -d ${JSON.stringify(tmp)}`)

const decode = (s) => {
  // strip XML tags to a fixpoint, then decode entities – &amp; strictly last,
  // otherwise "&amp;lt;" would double-unescape to "<"
  let out = s
  while (/<[^>]*>/.test(out)) out = out.replace(/<[^>]*>/g, '')
  return out
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#(\d+);/g, (_, d) => String.fromCharCode(d))
    .replace(/&amp;/g, '&')
    .trim()
}

const ss = readFileSync(join(tmp, 'xl/sharedStrings.xml'), 'utf8')
const strings = [...ss.matchAll(/<si>(.*?)<\/si>/gs)].map((m) => decode(m[1]))

const entries = new Map()
for (const sheetFile of readdirSync(join(tmp, 'xl/worksheets')).filter((f) => f.endsWith('.xml'))) {
  const sheet = readFileSync(join(tmp, 'xl/worksheets', sheetFile), 'utf8')
  for (const [, inner] of sheet.matchAll(/<row[^>]*>(.*?)<\/row>/gs)) {
    const cells = {}
    for (const c of inner.matchAll(/<c r="([A-Z]+)\d+"(?:[^>]*t="(\w+)")?[^>]*>(?:<v>(.*?)<\/v>)?/g)) {
      const [, col, type, v] = c
      cells[col] = type === 's' ? strings[Number(v)] : (v ?? '')
    }
    const name = (cells.A ?? '').replace(/\s+/g, ' ').trim()
    const code = (cells.B ?? '').trim()
    const period = (cells.C ?? '').replace(/\s+/g, ' ').trim()
    if (code && /^[A-Z]{1,5}$/.test(code) && name && name !== 'Code' && !entries.has(code)) {
      entries.set(code, { name, period })
    }
  }
}
rmSync(tmp, { recursive: true, force: true })

const sorted = [...entries.entries()].sort(([a], [b]) => a.localeCompare(b))
const lines = sorted.map(
  ([code, { name, period }]) =>
    `  ${code}: { name: ${JSON.stringify(name)}, period: ${JSON.stringify(period)} },`,
)

const out = `// AUTO-GENERATED by scripts/generate-tax-codes.mjs – do not edit by hand.
// Source: BMF "Verzeichnis der Abgabenarten" (bmf.gv.at), ${entries.size} codes.

export interface TaxCodeInfo {
  /** Official German name (legal term – shown untranslated in both UI languages). */
  name: string
  /** Period format the Finanzamt uses: "MM/JJJJ", "JJJJ", "KVJ" (quarter), … */
  period: string
}

export const TAX_CODES: Record<string, TaxCodeInfo> = {
${lines.join('\n')}
}

export function isKnownTaxCode(code: string): boolean {
  return code.toUpperCase() in TAX_CODES
}

export function taxCodeLabel(code: string): string {
  return TAX_CODES[code.toUpperCase()]?.name ?? code.toUpperCase()
}

/**
 * Period as printed on slips → human-readable:
 * "042026" → "04/2026", "01-032026" → "01-03/2026", "2026" stays.
 */
export function formatTaxPeriod(period: string): string {
  let m = /^(\\d{2})(\\d{4})$/.exec(period)
  if (m) return \`\${m[1]}/\${m[2]}\`
  m = /^(\\d{2}-\\d{2})\\/?(\\d{4})$/.exec(period)
  if (m) return \`\${m[1]}/\${m[2]}\`
  return period
}
`
writeFileSync(new URL('../src/lib/taxCodes.ts', import.meta.url), out)
console.log(`src/lib/taxCodes.ts regenerated: ${entries.size} codes`)
